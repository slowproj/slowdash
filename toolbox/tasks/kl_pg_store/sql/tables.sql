CREATE TABLE IF NOT EXISTS settings (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  schema_version integer NOT NULL DEFAULT 1,
  installed_at timestamptz NOT NULL DEFAULT now(),
  -- accepted ts range around now; no practical limit by default
  max_past interval NOT NULL DEFAULT '100 years' CHECK (max_past >= interval '0'),
  max_future interval NOT NULL DEFAULT '100 years' CHECK (max_future >= interval '0')
);
INSERT INTO settings DEFAULT VALUES ON CONFLICT DO NOTHING;

-- A name can have several channels (cids) for consecutive periods, each
-- valid in [valid_from, next valid_from).
CREATE TABLE IF NOT EXISTS channels (
  cid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (name <> '' AND name = btrim(name)),
  valid_from timestamptz NOT NULL DEFAULT '-infinity',
  type text NOT NULL CHECK (type IN ('double', 'integer', 'boolean', 'text', 'json')),
  unit text,
  description text,
  created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  UNIQUE (name, valid_from)
);

-- Changes of channels: one row per changed channel row (by a trigger, also
-- for direct SQL), and a summary row for each call of the functions that
-- move records (replace_channel(), merge_channel(), drop_channel()).
-- Records changed by direct SQL are not logged. Never deleted.
CREATE TABLE IF NOT EXISTS channel_log (
  log_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  logged_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  logged_by text NOT NULL DEFAULT session_user,
  xact_id xid8 NOT NULL DEFAULT pg_current_xact_id(),
  operation text NOT NULL,
  cid integer,
  old jsonb,
  new jsonb,
  detail text
);

-- Partitioned weekly by ensure_partition(). No foreign key to channels:
-- it would lock channels while a partition is attached, and cid integrity
-- is kept by the insert functions anyway (see check_integrity()).
CREATE TABLE IF NOT EXISTS raw_records (
  cid integer NOT NULL,
  ts timestamptz NOT NULL,
  inserted_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  value double precision,
  value_int bigint,
  value_text text,
  value_bool boolean,
  value_jsonb jsonb,
  CHECK (num_nonnulls(value, value_int, value_text, value_bool, value_jsonb) = 1)
) PARTITION BY RANGE (ts);

CREATE UNIQUE INDEX IF NOT EXISTS raw_records_cid_ts_key ON raw_records (cid, ts);
-- For time ranges over all channels. Small (rows arrive roughly in ts order).
CREATE INDEX IF NOT EXISTS raw_records_ts_brin ON raw_records USING brin (ts);

-- Latest value of each cid; derived from raw_records (see rebuild_latest()).
CREATE TABLE IF NOT EXISTS raw_latest (
  cid integer PRIMARY KEY,
  ts timestamptz NOT NULL,
  inserted_at timestamptz NOT NULL,
  value double precision,
  value_int bigint,
  value_text text,
  value_bool boolean,
  value_jsonb jsonb
) WITH (fillfactor = 50);

-- Every rejected input, as received, and the records removed by
-- merge_channel() and drop_channel(). Never deleted.
CREATE TABLE IF NOT EXISTS rejections (
  rejection_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  received_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  status text NOT NULL,
  cid integer,
  detail text,
  record jsonb
);
-- For the recent rejections. Small (rows arrive in received_at order).
CREATE INDEX IF NOT EXISTS rejections_received_at_brin ON rejections USING brin (received_at);
